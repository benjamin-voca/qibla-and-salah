"""Generate source-test/Golden.mc from api.aladhan.com (test-only oracle).

Usage: python3 tools/gen_golden.py [year]
The app itself never talks to the API; this just produces expected values so
the on-watch calculator can be unit-tested against a trusted source.
"""
import json
import sys
import urllib.request
from pathlib import Path

LAT, LNG, TUNE = 42.6629, 21.1655, "5,3,5,7,9,-1,0,8,-6"
ORDER = ["imsak", "fajr", "sunrise", "dhuhr", "asr", "sunset", "maghrib", "isha", "midnight"]  # PrayerCalc enum

year = int(sys.argv[1]) if len(sys.argv) > 1 else 2026
url = (f"https://api.aladhan.com/v1/calendar/{year}?latitude={LAT}&longitude={LNG}&method=13"
       f"&tune={TUNE}&timezonestring=Europe/Belgrade&latitudeAdjustmentMethod=1&school=0&midnightMode=0")
data = json.load(urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "namaz-tests"})))["data"]

rows = []
for month, days in sorted(data.items(), key=lambda kv: int(kv[0])):
    for e in days:
        g = e["date"]["gregorian"]
        day = int(g["day"])
        if day not in (1, 8, 15, 22, 29):
            continue
        tz = 2 if "CEST" in e["timings"]["Fajr"] else 1
        vals = []
        for k in ORDER:
            h, m = map(int, e["timings"][k.capitalize()].split()[0].split(":"))
            v = h * 60 + m
            if k == "midnight" and v < 12 * 60:
                v += 1440
            vals.append(v)
        rows.append(f"        [{year}, {int(month)}, {day}, {tz}, {vals}]")

out = Path(__file__).resolve().parent.parent / "source-test" / "Golden.mc"
out.parent.mkdir(exist_ok=True)
out.write_text(f"""// Generated by tools/gen_golden.py from api.aladhan.com — do not edit.
// Prishtina, Diyanet, tune={TUNE}. Row: [y, m, d, utcOffsetHours, [imsak..midnight minutes]]
import Toybox.Lang;

(:test)
module Golden {{
    const ROWS = [
{(","+chr(10)).join(rows)}
    ];
}}
""")
print(f"wrote {len(rows)} rows to {out}")
