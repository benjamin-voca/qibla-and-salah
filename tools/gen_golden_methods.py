"""Generate source-test/GoldenMethods.mc: every method vs api.aladhan.com (test-only oracle).

Each method is checked at a city where it is used, on 8 dates across 2026,
with angle-based high-latitude handling (the app's default).
"""
import json
import time
import urllib.request
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

# our index -> (aladhan id, lat, lng, tz name)
METHODS = {
    0: (13, 41.0082, 28.9784, "Europe/Istanbul"),
    1: (3, 51.5074, -0.1278, "Europe/London"),
    2: (2, 40.7128, -74.0060, "America/New_York"),
    3: (5, 30.0444, 31.2357, "Africa/Cairo"),
    4: (1, 24.8607, 67.0011, "Asia/Karachi"),
    5: (4, 21.4225, 39.8262, "Asia/Riyadh"),
    7: (7, 35.6892, 51.3890, "Asia/Tehran"),
    8: (0, 34.6416, 50.8746, "Asia/Tehran"),
    9: (8, 23.5880, 58.3829, "Asia/Muscat"),
    10: (9, 29.3759, 47.9774, "Asia/Kuwait"),
    11: (10, 25.2854, 51.5310, "Asia/Qatar"),
    12: (11, 1.3521, 103.8198, "Asia/Singapore"),
    13: (12, 48.8566, 2.3522, "Europe/Paris"),
    14: (14, 55.7963, 49.1088, "Europe/Moscow"),
    15: (16, 25.2048, 55.2708, "Asia/Dubai"),
    16: (17, 3.1390, 101.6869, "Asia/Kuala_Lumpur"),
    17: (18, 36.8065, 10.1815, "Africa/Tunis"),
    18: (19, 36.7538, 3.0588, "Africa/Algiers"),
    19: (20, -6.2088, 106.8456, "Asia/Jakarta"),
    20: (21, 33.5731, -7.5898, "Africa/Casablanca"),
    21: (22, 38.7223, -9.1393, "Europe/Lisbon"),
    22: (23, 31.9454, 35.9284, "Asia/Amman"),
}
ORDER = ["Imsak", "Fajr", "Sunrise", "Dhuhr", "Asr", "Sunset", "Maghrib", "Isha", "Midnight"]

rows = []
for idx, (api, lat, lng, tzname) in METHODS.items():
    tz = ZoneInfo(tzname)
    for month in (3, 6, 9, 12):
        # Tehran and Qum define midnight as halfway from sunset to Fajr (Jafari);
        # aladhan only applies that when asked (midnightMode=1).
        mm = 1 if idx in (7, 8) else 0
        url = (f"https://api.aladhan.com/v1/calendar/2026/{month}?latitude={lat}&longitude={lng}"
               f"&method={api}&school=0&latitudeAdjustmentMethod=3&midnightMode={mm}&timezonestring={tzname}")
        data = json.load(urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "namaz-tests"}), timeout=60))["data"]
        for e in data:
            day = int(e["date"]["gregorian"]["day"])
            if day not in (1, 15):
                continue
            off = datetime(2026, month, day, 12, tzinfo=tz).utcoffset().total_seconds() / 3600
            vals = []
            for k in ORDER:
                h, m = map(int, e["timings"][k].split()[0].split(":"))
                v = h * 60 + m
                if k == "Midnight" and v < 12 * 60:
                    v += 1440
                vals.append(v)
            rows.append(f"        [{idx}, {lat}d, {lng}d, 2026, {month}, {day}, {off}d, {vals}]")
        time.sleep(0.3)

out = Path(__file__).resolve().parent.parent / "source-test" / "GoldenMethods.mc"
out.write_text("""// Generated by tools/gen_golden_methods.py from api.aladhan.com — do not edit.
// Row: [methodIndex, lat, lng, y, m, d, utcOffsetHours, [imsak..midnight minutes]]
import Toybox.Lang;

(:test)
module GoldenMethods {
    const ROWS = [
""" + ",\n".join(rows) + """
    ];
}
""")
print(f"wrote {len(rows)} rows")
