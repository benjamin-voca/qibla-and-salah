"""Generate source-test/GoldenKosovo.mc from the Python reference (Kosovo method)."""
import sys
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parent))
import praytimes_ref as A

tz = ZoneInfo("Europe/Belgrade")
rows = []
for month in range(1, 13):
    for day in (1, 15):
        off = datetime(2026, month, day, 12, tzinfo=tz).utcoffset().total_seconds() / 3600
        t = A.compute(2026, month, day, 42.6629, 21.1655, off, A.KOSOVO, high_lat=A.HL_MIDDLE)
        rows.append(f"        [2026, {month}, {day}, {int(off)}, {t}]")
out = Path(__file__).resolve().parent.parent / "source-test" / "GoldenKosovo.mc"
out.write_text("""// Generated by tools/gen_golden_kosovo.py from tools/praytimes_ref.py — do not edit.
import Toybox.Lang;

(:test)
module GoldenKosovo {
    const ROWS = [
""" + ",\n".join(rows) + """
    ];
}
""")
print(f"wrote {len(rows)} rows")
