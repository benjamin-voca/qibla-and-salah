"""Generate source/HijriTable.mc: Umm al-Qura month starts (build-time only)."""
import json
import urllib.request
from datetime import date
from pathlib import Path

starts = {}  # (hy, hm) -> gregorian date of day 1
for year in range(2025, 2037):
    url = (f"https://api.aladhan.com/v1/calendar/{year}?latitude=42.6629&longitude=21.1655"
           f"&method=13&calendarMethod=UAQ")
    req = urllib.request.Request(url, headers={"User-Agent": "namaz-build"})
    data = json.load(urllib.request.urlopen(req, timeout=60))["data"]
    for month in data.values():
        for e in month:
            h, g = e["date"]["hijri"], e["date"]["gregorian"]
            if int(h["day"]) == 1:
                starts[(int(h["year"]), int(h["month"]["number"]))] = date(
                    int(g["year"]), int(g["month"]["number"]), int(g["day"]))

keys = sorted(starts)
# Keep only a contiguous run of months.
run = [keys[0]]
for k in keys[1:]:
    prev = run[-1]
    nxt = (prev[0] + (prev[1] == 12), prev[1] % 12 + 1)
    if k != nxt:
        break
    run.append(k)
epoch = date(1970, 1, 1)
days = [(starts[k] - epoch).days for k in run]
out = Path(__file__).resolve().parent.parent / "source" / "HijriTable.mc"
out.write_text(f"""// Generated by tools/gen_hijri.py (Umm al-Qura, via api.aladhan.com) — do not edit.
import Toybox.Lang;

module HijriTable {{
    const FIRST_YEAR = {run[0][0]};
    const FIRST_MONTH = {run[0][1]};
    // Day 1 of each consecutive Hijri month, as days since 1970-01-01.
    const STARTS = {days};
}}
""")
# Ramadan only, for the background service (Umm al-Qura's 120-min Isha):
# flat [start, end) day numbers, tiny compared to the full table.
ram = []
for i, (y, m) in enumerate(run[:-1]):
    if m == 9:
        ram += [days[i], days[i + 1]]
(out.parent / "RamadanTable.mc").write_text(f"""// Generated by tools/gen_hijri.py (Umm al-Qura, via api.aladhan.com) — do not edit.
import Toybox.Lang;

(:background :glance)
module RamadanTable {{
    // [start, end) of each Ramadan, as days since 1970-01-01.
    const DAYS = {ram};
}}
""")
print(f"{len(run)} months: {run[0]} .. {run[-1]}; {len(ram) // 2} Ramadans")
