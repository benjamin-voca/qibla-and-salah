        for d in (date(1900, 3, 1), date(2026, 2, 28), date(2026, 3, 1), date(2028, 2, 29), date(2099, 12, 31)):
            self.assertEqual(R.day_number(d.year, d.month, d.day), (d - epoch).days, d)


