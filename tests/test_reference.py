def load_rows(name: str) -> list:
    """Parse `const ROWS = [...]` from a source-test/*.mc file."""
    src = (ROOT / "source-test" / name).read_text(encoding="utf-8")
    src = re.sub(r"//[^\n]*", "", src)
    body = re.search(r"const\s+ROWS\s*=\s*(\[.*\])\s*;", src, flags=re.S).group(1)
    body = re.sub(r"(\d)d\b", r"\1", body)  # 3.0d -> 3.0
    return ast.literal_eval(body)


# ---- Monkey C test helpers (PropertyTest.mc: Gen, P) -------------------------------

class Gen:
    """Port of the Monkey C `Gen` module (32-bit wrapping LCG)."""

    def __init__(self, seed: int):
        self.state = seed

    def next(self) -> int:
        s = (self.state * 1664525 + 1013904223) & 0xFFFFFFFF
        self.state = s - (1 << 32) if s & 0x80000000 else s
        return self.state & 0x7FFFFFFF

    def unit(self) -> float:
        return self.next() / 2147483647.0

    def range(self, a: float, b: float) -> float:
        return a + (b - a) * self.unit()

    def int(self, a: int, b: int) -> int:
        return a + self.next() % (b - a + 1)

    def bool(self) -> bool:
        return (self.next() & 1) == 1

    def place(self, lat_min: float, lat_max: float) -> list:
        lng = self.range(-180.0, 180.0)
        tz = mc_round(lng / 15.0)
        if self.int(0, 9) == 0:
            tz += 0.5
        return [self.int(2000, 2099), self.int(1, 12), self.int(1, 28),
                self.range(lat_min, lat_max), lng, tz]


def mc_round(x: float) -> float:
    return math.copysign(math.floor(abs(x) + 0.5), x)


ALL_METHODS = 23
ZERO_TUNE = [0] * 9


def calc(c: list, method: int, asr: int, hl: int) -> list[int]:
    return R.compute(c[0], c[1], c[2], c[3], c[4], c[5], method, ZERO_TUNE, asr, hl)


def sunlen(t: list[int]) -> int:
    return t[R.SUNSET] - t[R.SUNRISE]


def describe(c: list) -> str:
    return f"{c[0]}-{c[1]}-{c[2]} lat={c[3]:.3f} lng={c[4]:.3f} tz={c[5]}"


