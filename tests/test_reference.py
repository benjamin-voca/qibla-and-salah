class GoldenTest(unittest.TestCase):
    def assert_rows(self, rows, fn, tol, label):
        bad = []
        for row in rows:
            key, exp = fn(row)
            got = key()
            for i, e in enumerate(exp):
                if abs(got[i] - e) > tol(i):
                    bad.append(f"{label} {row[:-1]} idx {R.NAMES[i]}: got {got[i]} expected {e}")
        self.assertFalse(bad, "\n".join(bad[:30]) + f"\n({len(bad)} values out of tolerance)")

    def test_golden_methods_aladhan(self):
        rows = load_rows("GoldenMethods.mc")
        self.assertGreater(len(rows), 100)
        # Every method except the Kosovo takvim fit, which aladhan does not have.
        self.assertEqual({r[0] for r in rows}, set(range(R.METHOD_COUNT)) - {R.KOSOVO})

        def fn(r):
            m, lat, lng, y, mo, d, tz, exp = r
            return (lambda: R.compute(y, mo, d, lat, lng, tz, m, None, 1, R.HL_ANGLE)), exp

        self.assert_rows(rows, fn, lambda i: 2 if i == R.ASR else 1, "method")

    def test_golden_diyanet_prishtina(self):
        # aladhan's tune=5,3,5,7,9,-1,0,8,-6 replaces Diyanet's own offsets; ours
        # adds to them, so this is that list minus Diyanet's offsets.
        tune = [5, 3, 12, 2, 5, -8, 0, 8, -6]
        rows = load_rows("Golden.mc")
        self.assertGreater(len(rows), 40)

        def fn(r):
            y, mo, d, tz, exp = r
            return (lambda: R.compute(y, mo, d, *PRISHTINA, float(tz), 0, tune, 1, R.HL_MIDDLE)), exp

        # Same tolerance as prayerCalcMatchesAladhan on the watch.
        self.assert_rows(rows, fn, lambda i: 1 if i == R.ASR else 0, "diyanet")

    def test_golden_kosovo_exact(self):
        rows = load_rows("GoldenKosovo.mc")
        self.assertEqual(len(rows), 24)

        def fn(r):
            y, mo, d, tz, exp = r
            return (lambda: R.compute(y, mo, d, *PRISHTINA, float(tz), R.KOSOVO, [], 1, R.HL_MIDDLE)), exp

        # Generated from this reference: must match exactly.
        self.assert_rows(rows, fn, lambda i: 0, "kosovo")


# ---- prayer-time properties (PropertyTest.mc) -------------------------------------

class PrayerPropertiesTest(unittest.TestCase):
    def test_day_is_ordered(self):
        g = Gen(1)
        for _ in range(150):
            c = g.place(-55.0, 55.0)
            m = g.int(0, ALL_METHODS - 1)
            t = calc(c, m, g.int(1, 2), g.int(0, 2))
            s = f"{describe(c)} method={m} {t}"
            self.assertLessEqual(t[R.IMSAK], t[R.FAJR], s)
            self.assertLess(t[R.FAJR], t[R.SUNRISE], s)
            self.assertLess(t[R.SUNRISE], t[R.DHUHR], s)
            self.assertLess(t[R.DHUHR], t[R.ASR], s)
            self.assertLess(t[R.ASR], t[R.SUNSET], s)
            self.assertLessEqual(t[R.SUNSET], t[R.MAGHRIB], s)
            self.assertLess(t[R.MAGHRIB], t[R.ISHA], s)
            self.assertLess(t[R.MAGHRIB], t[R.MIDNIGHT], s)

    def test_dhuhr_is_solar_noon(self):
        g = Gen(2)
        for _ in range(150):
            c = g.place(-60.0, 60.0)
            t = calc(c, 1, 1, R.HL_ANGLE)
            mean_noon = 720.0 + 60.0 * (c[5] - c[4] / 15.0)
            eot = t[R.DHUHR] - mean_noon
            mid = (t[R.SUNRISE] + t[R.SUNSET]) / 2.0
            self.assertLessEqual(abs(eot), 17.5, f"{describe(c)} eot={eot}")
            self.assertLessEqual(abs(t[R.DHUHR] - mid), 2.0, describe(c))

    def test_timezone_shifts_everything(self):
        g = Gen(3)
        for _ in range(100):
            c = g.place(-60.0, 60.0)
            m = g.int(0, ALL_METHODS - 1)
            a = calc(c, m, 1, R.HL_ANGLE)
            b = calc(c[:5] + [c[5] + 1.0], m, 1, R.HL_ANGLE)
            for i in range(R.COUNT):
                self.assertLessEqual(abs(b[i] - a[i] - 60), 1, f"{describe(c)} method={m} idx={i}")

    def test_longitude_and_clock_cancel(self):
        g = Gen(4)
        for _ in range(100):
            c = g.place(-50.0, 50.0)
            if c[4] > 160.0:
                continue
            a = calc(c, 1, 1, R.HL_ANGLE)
            b = calc(c[:4] + [c[4] + 15.0, c[5] + 1.0], 1, 1, R.HL_ANGLE)
            for i in range(R.COUNT):
                self.assertLessEqual(abs(b[i] - a[i]), 1, f"{describe(c)} idx={i} {a[i]} vs {b[i]}")

    def test_tune_is_additive(self):
        g = Gen(5)
        for _ in range(100):
            c = g.place(-55.0, 55.0)
            m = g.int(0, ALL_METHODS - 1)
            tune = [g.int(-30, 30) for _ in range(9)]
            base = calc(c, m, 1, R.HL_ANGLE)
            tuned = R.compute(c[0], c[1], c[2], c[3], c[4], c[5], m, tune, 1, R.HL_ANGLE)
            for i, k in enumerate(R.TUNE_ORDER):
                self.assertLessEqual(abs(tuned[k] - base[k] - tune[i]), 1,
                                     f"{describe(c)} method={m} idx={k} tune={tune[i]}")

    def test_hanafi_asr_is_later(self):
        g = Gen(6)
        for _ in range(150):
            c = g.place(-50.0, 50.0)
            m = g.int(0, ALL_METHODS - 1)
            std = calc(c, m, 1, R.HL_ANGLE)
            han = calc(c, m, 2, R.HL_ANGLE)
            self.assertGreater(han[R.ASR], std[R.ASR], f"{describe(c)} method={m}")
            self.assertLess(han[R.ASR], han[R.SUNSET], f"{describe(c)} method={m}")

    def test_fixed_minute_rules(self):
        g = Gen(7)
        for _ in range(100):
            c = g.place(-55.0, 55.0)
            uaq, gulf, qatar, lisbon, jordan, kosovo, mwl = (
                calc(c, m, 1, R.HL_ANGLE) for m in (5, 9, 11, 21, 22, R.KOSOVO, 1))
            uaq_isha = 120 if R.is_ramadan(c[0], c[1], c[2]) else 90
            s = describe(c)
            self.assertLessEqual(abs(uaq[R.ISHA] - uaq[R.MAGHRIB] - uaq_isha), 1, s)
            self.assertLessEqual(abs(gulf[R.ISHA] - gulf[R.MAGHRIB] - 90), 1, s)
            self.assertLessEqual(abs(qatar[R.ISHA] - qatar[R.MAGHRIB] - 90), 1, s)
            self.assertLessEqual(abs(lisbon[R.MAGHRIB] - lisbon[R.SUNSET] - 3), 1, s)
            self.assertLessEqual(abs(lisbon[R.ISHA] - lisbon[R.MAGHRIB] - 77), 1, s)
            self.assertLessEqual(abs(jordan[R.MAGHRIB] - jordan[R.SUNSET] - 5), 1, s)
            self.assertLessEqual(abs(mwl[R.FAJR] - mwl[R.IMSAK] - 10), 1, s)
            self.assertEqual(kosovo[R.IMSAK], kosovo[R.FAJR], s)

    def test_umm_al_qura_ramadan_isha(self):
        # The random dates above rarely land in Ramadan: check it explicitly.
        makkah = (21.4225, 39.8262, 3.0)
        normal = R.compute(2026, 2, 10, *makkah, 5)
        ramadan = R.compute(2026, 3, 1, *makkah, 5)
        self.assertEqual(normal[R.ISHA] - normal[R.MAGHRIB], 90)
        self.assertEqual(ramadan[R.ISHA] - ramadan[R.MAGHRIB], 120)

    def test_midnight_rules(self):
        g = Gen(8)
        for _ in range(100):
            c = g.place(-55.0, 55.0)
            std = calc(c, 1, 1, R.HL_ANGLE)
            jaf = calc(c, 7, 1, R.HL_ANGLE)
            std_mid = (std[R.SUNSET] + std[R.SUNRISE] + 1440) / 2.0
            jaf_mid = (jaf[R.SUNSET] + jaf[R.FAJR] + 1440) / 2.0
            self.assertLessEqual(abs(std[R.MIDNIGHT] - std_mid), 1.0, describe(c))
            self.assertLessEqual(abs(jaf[R.MIDNIGHT] - jaf_mid), 1.0, describe(c))

    def test_twilight_angle_is_monotonic(self):
        g = Gen(9)
        for _ in range(100):
            c = g.place(-45.0, 45.0)
            isna, mwl, egypt, sing, kar = (calc(c, m, 1, R.HL_ANGLE) for m in (2, 1, 3, 12, 4))
            self.assertTrue(isna[R.FAJR] >= mwl[R.FAJR] >= egypt[R.FAJR] >= sing[R.FAJR], describe(c))
            self.assertTrue(isna[R.ISHA] <= mwl[R.ISHA] <= egypt[R.ISHA] <= kar[R.ISHA], describe(c))

    def test_day_length(self):
        g = Gen(10)
        for _ in range(60):
            c = g.place(-0.5, 0.5)
            n = sunlen(calc(c, 1, 1, R.HL_ANGLE))
            self.assertTrue(715 <= n <= 745, f"equator {describe(c)} len={n}")
        for _ in range(60):
            c = g.place(-60.0, 60.0)
            c[1] = 3 if g.bool() else 9
            c[2] = 20 if c[1] == 3 else 22
            n = sunlen(calc(c, 1, 1, R.HL_ANGLE))
            self.assertTrue(705 <= n <= 775, f"equinox {describe(c)} len={n}")
        for _ in range(60):
            a = g.range(-60.0, 59.0)
            b = g.range(a, 60.0)
            lng = g.range(-180.0, 180.0)
            tz = mc_round(lng / 15.0)
            y = g.int(2000, 2099)
            L = lambda mo, lat: sunlen(R.compute(y, mo, 21, lat, lng, tz, 1, ZERO_TUNE, 1, R.HL_ANGLE))
            s = describe([y, 6, 21, a, lng, tz]) + f" b={b}"
            self.assertLessEqual(L(6, a), L(6, b) + 1, "June days longer further north " + s)
            self.assertGreaterEqual(L(12, a) + 1, L(12, b), "December days shorter further north " + s)

    def test_polar_clamp(self):
        """Beyond 66° the times of latitude 45° are used (Islamic Fiqh Council)."""
        g = Gen(11)
        for _ in range(100):
            north = g.bool()
            c = g.place(66.01, 90.0)
            if not north:
                c[3] = -c[3]
            m = g.int(0, ALL_METHODS - 1)
            t = calc(c, m, 1, g.int(0, 2))
            c45 = c[:3] + [45.0 if north else -45.0] + c[4:]
            hl = g.int(0, 2)
            a = calc(c, m, 1, hl)
            b = calc(c45, m, 1, hl)
            s = f"{describe(c)} method={m} {t}"
            self.assertTrue(all(-1440 < v < 2 * 1440 for v in t), "finite " + s)
            self.assertTrue(t[R.FAJR] <= t[R.SUNRISE] <= t[R.DHUHR] <= t[R.SUNSET], "ordered " + s)
            self.assertEqual(a, b, "beyond 66° equals 45° " + s)


# ---- Qibla properties -------------------------------------------------------------

EARTH_R = 6371.0


def dist(lat1, lng1, lat2, lng2):
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lng2 - lng1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2.0 * EARTH_R * math.atan2(math.sqrt(a), math.sqrt(1 - a))


def travel(lat, lng, deg, km):
    p1, l1, b, d = math.radians(lat), math.radians(lng), math.radians(deg), km / EARTH_R
    p2 = math.asin(math.sin(p1) * math.cos(d) + math.cos(p1) * math.sin(d) * math.cos(b))
    l2 = l1 + math.atan2(math.sin(b) * math.sin(d) * math.cos(p1), math.cos(d) - math.sin(p1) * math.sin(p2))
    return math.degrees(p2), math.degrees(l2)


class QiblaPropertiesTest(unittest.TestCase):
    def test_kaaba_constants(self):
        self.assertEqual((Q.KAABA_LAT, Q.KAABA_LNG), (21.4225, 39.8262))

    def test_range(self):
        g = Gen(21)
        for _ in range(300):
            lat, lng = g.range(-89.0, 89.0), g.range(-180.0, 180.0)
            b = Q.bearing(lat, lng)
            self.assertTrue(0.0 <= b < 360.0, f"lat={lat} lng={lng} b={b}")

    def test_on_meridian(self):
        g = Gen(22)
        for _ in range(100):
            north = g.range(Q.KAABA_LAT + 0.5, 85.0)
            south = g.range(-85.0, Q.KAABA_LAT - 0.5)
            bn, bs = Q.bearing(north, Q.KAABA_LNG), Q.bearing(south, Q.KAABA_LNG)
            from_north = bs if bs < 180.0 else bs - 360.0
            self.assertLess(abs(bn - 180.0), 0.01, f"lat={north} b={bn}")
            self.assertLess(abs(from_north), 0.01, f"lat={south} b={bs}")

    def test_points_towards_kaaba(self):
        g = Gen(23)
        tested = 0
        for _ in range(400):
            if tested >= 200:
                break
            lat, lng = g.range(-80.0, 80.0), g.range(-180.0, 180.0)
            d0 = dist(lat, lng, Q.KAABA_LAT, Q.KAABA_LNG)
            if d0 < 300.0 or d0 > 19700.0:
                continue
            tested += 1
            p = travel(lat, lng, Q.bearing(lat, lng), 10.0)
            d1 = dist(p[0], p[1], Q.KAABA_LAT, Q.KAABA_LNG)
            self.assertTrue(9.9 < d0 - d1 <= 10.01, f"lat={lat} lng={lng} closer by {d0 - d1}")
        self.assertGreater(tested, 100)

    def test_known_cities(self):
        cases = [("Prishtina", 42.6629, 21.1655, 137.85), ("London", 51.5074, -0.1278, 119.0),
                 ("New York", 40.7128, -74.0060, 58.5), ("Jakarta", -6.2088, 106.8456, 295.2),
                 ("Sydney", -33.8688, 151.2093, 277.5), ("Cape Town", -33.9249, 18.4241, 23.3)]
        for name, lat, lng, exp in cases:
            with self.subTest(name):
                self.assertLess(abs(Q.bearing(lat, lng) - exp), 0.5)


