class TablesTest(unittest.TestCase):
    def test_method_table_shape(self):
        self.assertEqual(len(R.METHOD_DATA), R.METHOD_COUNT * R.METHOD_WIDTH)
        for i in range(R.METHOD_COUNT):
            r = R.method_row(i)
            self.assertGreaterEqual(len(r), R.ROW_FIELDS, i)
            self.assertTrue(all(isinstance(v, int) for v in r))
            self.assertGreater(r[0], 0, f"method {i}: fajr angle")
            self.assertIn(r[2], (0, 1))
            self.assertIn(r[4], (0, 1))
            self.assertIn(r[6], (0, 1))

    def test_known_rows(self):
        self.assertEqual(R.method_row(0)[:18], [1800, 1700, 0, 0, 0, 10, 0, 0, 0, 0, 0, -7, 5, 4, 7, 7, 0, 0])
        self.assertEqual(R.method_row(5)[:9], [1850, 9000, 1, 0, 0, 10, 0, 120, 0])
        self.assertEqual(R.method_row(R.KOSOVO)[:9], [1850, 1525, 0, 0, 0, 0, 0, 0, 1])
        self.assertEqual(R.method_row(7)[3:7], [450, 1, 10, 1])
        self.assertEqual(R.method_row(21)[:4], [1800, 7700, 1, 300])

    def test_other_constants(self):
        self.assertEqual(R.TUNE_ORDER, [R.IMSAK, R.FAJR, R.SUNRISE, R.DHUHR, R.ASR,
                                        R.MAGHRIB, R.SUNSET, R.ISHA, R.MIDNIGHT])
        self.assertEqual(R.SEASONAL_TARGETS, [R.FAJR, R.SUNRISE, R.DHUHR, R.ASR, R.MAGHRIB, R.ISHA])
        self.assertEqual(len(R.SEASONAL_KOSOVO), 6)
        self.assertTrue(all(len(c) == 3 for c in R.SEASONAL_KOSOVO))
        self.assertAlmostEqual(R.SEASONAL_KOSOVO[5][0], 21.308, places=5)
        self.assertEqual(R.RISESET, 0.833)
        self.assertEqual(R.MAX_LAT, 66.0)
        self.assertEqual(R.POLAR_LAT, 45.0)

    def test_ramadan_table(self):
        d = R.RAMADAN_DAYS
        self.assertEqual(len(d) % 2, 0)
        self.assertEqual(d, sorted(d))
        for i in range(0, len(d), 2):
            self.assertIn(d[i + 1] - d[i], (29, 30))
        # Ramadan 1447 began 2026-02-18 (Umm al-Qura).
        self.assertFalse(R.is_ramadan(2026, 2, 17))
        self.assertTrue(R.is_ramadan(2026, 2, 18))
        self.assertTrue(R.is_ramadan(2026, 3, 19))
        self.assertFalse(R.is_ramadan(2026, 3, 20))

    def test_day_number(self):
        self.assertEqual(R.day_number(1970, 1, 1), 0)
        self.assertEqual(R.day_number(2000, 1, 1), 10957)
